/* Twiddle web flasher page. Plain JavaScript, no framework, no third-party requests.
   Reads index.json (generated by scripts/gen_site.py) and config.json. All data is put in the page with textContent. */
(function () {
  "use strict";
  var $ = function (id) { return document.getElementById(id); };
  var state = { data: null, board: null, version: null };

  function el(tag, props, children) {
    var e = document.createElement(tag);
    Object.keys(props || {}).forEach(function (k) {
      if (k === "text") e.textContent = props[k];
      else if (k === "class") e.className = props[k];
      else e.setAttribute(k, props[k]);
    });
    (children || []).forEach(function (c) { e.appendChild(typeof c === "string" ? document.createTextNode(c) : c); });
    return e;
  }

  /* ---- theme toggle: auto -> dark -> light ---- */
  var themes = ["auto", "dark", "light"];
  function applyTheme(t) {
    var root = document.documentElement;
    if (t === "auto") root.removeAttribute("data-theme"); else root.setAttribute("data-theme", t);
    var b = $("theme");
    b.textContent = "Theme: " + t;
    b.setAttribute("aria-label", "Colour theme: " + t + ". Activate to change.");
  }
  var theme = "auto";
  try { theme = localStorage.getItem("theme") || "auto"; } catch (e) { /* storage may be blocked */ }
  if (themes.indexOf(theme) < 0) theme = "auto";
  applyTheme(theme);
  $("theme").addEventListener("click", function () {
    theme = themes[(themes.indexOf(theme) + 1) % themes.length];
    try { localStorage.setItem("theme", theme); } catch (e) { /* ignore */ }
    applyTheme(theme);
  });

  /* ---- browser check ---- */
  var serialOk = "serial" in navigator;
  var secureOk = window.isSecureContext;
  (function () {
    var box = $("browser-status");
    if (serialOk && secureOk) {
      box.className = "notice ok";
      box.textContent = "Your browser can flash boards over USB. You also need a USB data cable (a charge-only cable will not work).";
    } else if (!secureOk) {
      box.className = "notice danger";
      box.textContent = "This page is not served over HTTPS, so the browser blocks USB access. Open the https:// address of this site.";
    } else {
      box.className = "notice danger";
      box.textContent = "This browser cannot flash. Use desktop Chrome or Edge on Windows, macOS, Linux or ChromeOS. Safari, Firefox, iPhone/iPad and Android browsers cannot flash. You can still read the instructions below.";
    }
    $("install-slot").hidden = !(serialOk && secureOk);
    if (serialOk && secureOk) {
      var s = document.createElement("script");
      s.type = "module";
      s.src = "vendor/esp-web-tools/install-button.js";
      document.head.appendChild(s);
    }
  })();

  /* ---- data ---- */
  function load() {
    Promise.all([
      fetch("index.json", { cache: "no-cache" }).then(function (r) { if (!r.ok) throw new Error("index.json: HTTP " + r.status); return r.json(); }),
      fetch("config.json", { cache: "no-cache" }).then(function (r) { return r.ok ? r.json() : {}; }).catch(function () { return {}; })
    ]).then(function (res) {
      state.data = res[0];
      if (res[1].source_url) $("source-link").href = res[1].source_url;
      renderCards();
    }).catch(function (e) {
      var box = $("load-error");
      box.hidden = false;
      box.textContent = "Could not load the list of boards (" + e.message + "). Reload the page.";
    });
  }

  function badge(text, cls) { return el("span", { "class": "badge " + (cls || ""), text: text }); }

  function renderCards() {
    var ul = $("cards");
    ul.textContent = "";
    state.data.boards.forEach(function (b) {
      var avail = b.status === "available" && b.versions.length > 0;
      var btn = el("button", { type: "button", "class": "card", "aria-pressed": "false", "data-board": b.id });
      var img = el("img", { src: b.photo || "", alt: b.photo_is_placeholder ? "Placeholder picture, not a photo of the real board" : b.short });
      btn.appendChild(img);
      btn.appendChild(el("h3", { text: b.short || b.name }));
      btn.appendChild(el("span", { text: b.summary || "" }));
      var row = el("span");
      if (b.status === "unavailable") row.appendChild(badge("Not yet available", "no"));
      else if (!avail) row.appendChild(badge("No tested image published yet", "no"));
      else row.appendChild(badge("Latest tested: " + b.latest, "ok"));
      if (b.photo_is_placeholder) row.appendChild(document.createTextNode(" ")), row.appendChild(badge("Placeholder photo"));
      btn.appendChild(row);
      if (b.status === "unavailable") btn.appendChild(el("span", { text: b.unavailable_reason || "" }));
      if (!avail) {
        btn.setAttribute("aria-disabled", "true");
        btn.removeAttribute("aria-pressed");
      }
      btn.addEventListener("click", function () { if (avail) selectBoard(b.id); });
      var li = el("li");
      li.appendChild(btn);
      ul.appendChild(li);
    });
  }

  function selectBoard(id) {
    var b = state.data.boards.filter(function (x) { return x.id === id; })[0];
    state.board = b;
    Array.prototype.forEach.call(document.querySelectorAll(".card[data-board]"), function (c) {
      if (c.getAttribute("aria-pressed") !== null) c.setAttribute("aria-pressed", String(c.getAttribute("data-board") === id));
    });
    var info = $("board-info");
    info.textContent = "";
    info.appendChild(el("h3", { text: b.name }));
    info.appendChild(el("p", { "class": "", text: "How to recognise this board:" }));
    var ul = el("ul");
    (b.identify || []).forEach(function (t) { ul.appendChild(el("li", { text: t })); });
    info.appendChild(ul);
    if (b.variants && b.variants.length) {
      var vl = el("ul");
      b.variants.forEach(function (v) { vl.appendChild(el("li", {}, [el("strong", { text: v.label + ": " }), v.hint])); });
      info.appendChild(el("p", { text: "Versions of this board (same installer):" }));
      info.appendChild(vl);
    }
    if (b.port_hint) info.appendChild(el("p", { text: b.port_hint }));

    var dl = $("dlmode-list");
    dl.textContent = "";
    (b.download_mode || []).forEach(function (t) { dl.appendChild(el("li", { text: t })); });
    var ph = $("board-photo");
    ph.src = b.photo || "";
    ph.alt = b.photo_is_placeholder ? "Placeholder picture, not a photo of the real board" : "The " + b.short + " board";
    $("photo-note").hidden = !b.photo_is_placeholder;

    $("p4-note").hidden = b.chipFamily !== "ESP32-P4";
    var nl = $("board-notes");
    nl.textContent = "";
    (b.notes || []).forEach(function (t) { nl.appendChild(el("li", { text: t })); });
    nl.hidden = !(b.notes && b.notes.length);

    var c = $("caution");
    c.hidden = !b.caution;
    c.textContent = b.caution || "";

    var sel = $("version");
    sel.textContent = "";
    b.versions.forEach(function (v) {
      sel.appendChild(el("option", { value: v.version, text: v.version + (v.version === b.latest ? " (latest tested)" : "") + " - " + v.released }));
    });
    $("installer").hidden = false;
    selectVersion(b.latest);
    $("h-install").focus();
    $("installer").scrollIntoView({ behavior: window.matchMedia("(prefers-reduced-motion: reduce)").matches ? "auto" : "smooth", block: "start" });
  }

  function currentMode() { return document.querySelector('input[name="mode"]:checked').value; }

  function selectVersion(ver) {
    var v = state.board.versions.filter(function (x) { return x.version === ver; })[0];
    state.version = v;
    $("version").value = ver;
    var meta = $("version-meta");
    meta.textContent = "";
    meta.appendChild(badge("Tested on chip " + v.tested.chip_rev + ", " + v.tested.date, "ok"));
    if (v.tested.variants_tested && v.tested.variants_tested.length) {
      meta.appendChild(document.createTextNode(" "));
      meta.appendChild(badge("Board versions tested: " + v.tested.variants_tested.join(", ")));
    }
    $("changelog").textContent = v.notes || "No release notes were published for this version.";
    var tb = document.querySelector("#files tbody");
    tb.textContent = "";
    v.files.forEach(function (f) {
      var tr = el("tr");
      tr.appendChild(el("td", { text: f.part }));
      tr.appendChild(el("td", { text: "0x" + f.offset.toString(16) + " (" + f.offset + ")" }));
      tr.appendChild(el("td", { text: f.size + " bytes" }));
      tr.appendChild(el("td", {}, [el("code", { text: f.sha256 })]));
      tb.appendChild(tr);
    });
    $("sums-link").href = v.sha256sums;
    $("lic-link").href = "licenses/" + state.board.id + "/" + v.version + "/";
    setManifest();
  }

  function setManifest() {
    var mode = currentMode();
    $("mode-warn").hidden = mode !== "new";
    $("update-warn").hidden = mode !== "update";
    var path = state.version["manifest_" + mode];
    var btn = $("install-button");
    btn.setAttribute("manifest", path);
    btn.setAttribute("data-manifest-resolved", new URL(path, location.href).href);
  }

  $("version").addEventListener("change", function () { selectVersion(this.value); });
  Array.prototype.forEach.call(document.querySelectorAll('input[name="mode"]'), function (r) {
    r.addEventListener("change", function () { if (state.version) setManifest(); });
  });

  load();
})();
